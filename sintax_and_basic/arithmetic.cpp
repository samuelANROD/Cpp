#include <iostream>

int main () {

    int a = 10;
    int b = 3;

    // Adição
    std::cout << "Addition: " << a + b << std::endl;

    // Subtração
    std::cout << "Subtraction: " << a - b << std::endl;

    // Multiplicação
    std::cout << "Multiplication: " << a * b << std::endl;

    // Divisão
    std::cout << "Division: " << a / b << std::endl;

    // Resto da divisão (módulo)
    std::cout << "Modulo: " << a % b << std::endl;

    return 0;
}